static void restart() {  
  /* Set the initial program counter. */
  cpu.pc = RESET_VECTOR;

  /* The zero register is always 0. */
  cpu.gpr[0] = 0;
  cpu.csr[1] = 0x1800;
}


void init_isa() {
  /* Load build-in image. */
  memcpy(guest_to_host(RESET_VECTOR), img, sizeof(img));

  /* Initialize this vertual computer system. */
  restart();
}
